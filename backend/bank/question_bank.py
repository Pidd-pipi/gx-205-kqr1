def build_pool():
    """构建完整题库，id 由 题型/难度/序号 派生，保证多次构建完全一致。"""
    pool = []
    for type_index, (type_key, type_name) in enumerate(QUESTION_TYPES, start=1):
        cells = _BUILDERS[type_key]()
        for difficulty_index, difficulty in enumerate(DIFFICULTIES):
            questions = cells[difficulty]
            expected = CELL_SIZE[difficulty]
            if len(questions) != expected:
                raise ValueError(f"{type_name}/{difficulty} 题量应为 {expected}，实际为 {len(questions)}")
            for serial, question in enumerate(questions, start=1):
                question_id = type_index * 1000 + difficulty_index * 100 + serial
                options = list(question["options"])
                random.Random(question_id).shuffle(options)
                pool.append(
                    {
                        "id": question_id,
                        "type": type_name,
                        "difficulty": difficulty,
                        "stem": question["stem"],
                        "options": options,
                        "answer": question["answer"],
                        "explanation": question["explanation"],
                        "knowledge": question["knowledge"],
                    }
                )
    return pool


POOL = build_pool()

POOL_BY_TYPE_DIFF = {}
for _question in POOL:
    POOL_BY_TYPE_DIFF.setdefault((_question["type"], _question["difficulty"]), []).append(_question)
