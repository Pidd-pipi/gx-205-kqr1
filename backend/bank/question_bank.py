def _q(stem, answer, distractors, explanation, knowledge):
    return {
        "stem": stem,
        "options": [str(answer), *[str(item) for item in distractors]],
        "answer": str(answer),
        "explanation": explanation,
        "knowledge": knowledge,
    }


# ---------------------------------------------------------------- 数字推理

def _arith(a0, d, n=5):
    terms = [a0 + i * d for i in range(n)]
    nxt = a0 + n * d
    stem = "，".join(map(str, terms)) + "，下一项是多少？"
    sign = "+" if d >= 0 else "-"
    expl = f"相邻两项的差恒为 {abs(d)}，因此下一项为 {terms[-1]}{sign}{abs(d)}={nxt}。"
    return stem, nxt, expl


def _geom(a0, r, n=5):
    terms = [a0 * r ** i for i in range(n)]
    nxt = a0 * r ** n
    stem = "，".join(map(str, terms)) + "，下一项是多少？"
    expl = f"后一项是前一项的 {r} 倍，因此下一项为 {terms[-1]}×{r}={nxt}。"
    return stem, nxt, expl


def _second_order(a0, d0, k, n=5):
    terms, d = [a0], d0
    for _ in range(n - 1):
        terms.append(terms[-1] + d)
        d += k
    nxt = terms[-1] + d
    diffs = "、".join(str(d0 + i * k) for i in range(n - 1))
    stem = "，".join(map(str, terms)) + "，下一项是多少？"
    expl = f"相邻差依次为 {diffs}，差值每次增加 {k}，下一差为 {d}，故答案为 {terms[-1]}+{d}={nxt}。"
    return stem, nxt, expl


def _recur(a0, k, b, n=5):
    terms = [a0]
    for _ in range(n - 1):
        terms.append(terms[-1] * k + b)
    nxt = terms[-1] * k + b
    sign = "+" if b >= 0 else "-"
    stem = "，".join(map(str, terms)) + "，下一项是多少？"
    expl = f"规律为前一项×{k}{sign}{abs(b)}，故下一项为 {terms[-1]}×{k}{sign}{abs(b)}={nxt}。"
    return stem, nxt, expl


def _num(stem_answer_expl, knowledge):
    stem, answer, expl = stem_answer_expl
    return _q(stem, answer, [answer - 2, answer + 2, answer + 4], expl, knowledge)


